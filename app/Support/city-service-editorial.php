function aloCityServiceChoices(string $citySlug, string $serviceSlug, string $purpose, int $total, int $take): array
{
    $indices = range(0, $total - 1);
    $seed = $citySlug . '|' . $serviceSlug . '|' . $purpose . '|v1';
    usort($indices, static function (int $a, int $b) use ($seed): int {
        $ha = hash('sha256', $seed . '|' . $a);
        $hb = hash('sha256', $seed . '|' . $b);
        return strcmp($ha, $hb) ?: ($a <=> $b);
    });
    return array_slice($indices, 0, min($take, $total));
}

